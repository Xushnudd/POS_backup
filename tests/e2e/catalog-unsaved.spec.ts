import {test,expect} from '@playwright/test'
import {PrismaClient} from '@prisma/client'
import {randomUUID} from 'node:crypto'
const connection=new URL(process.env.DATABASE_URL??'')
if(connection.hostname!=='127.0.0.1'||connection.port!=='55439'||connection.pathname!=='/pos_test')throw new Error('Isolated database only')
const db=new PrismaClient(),organizations:string[]=[],users:string[]=[]
test.afterAll(async()=>{await db.organization.deleteMany({where:{id:{in:organizations}}});await db.user.deleteMany({where:{id:{in:users}}});await db.$disconnect()})
test('Catalog forms preserve unsaved data on cancel, navigation and failed save; successful saves reset the guard',async({page})=>{
 const registered=await page.request.post('/api/auth/register',{headers:{Origin:'https://localhost:3100'},data:{fullName:'Unsaved catalog owner',phone:'unsaved-'+randomUUID(),password:'test-only-password',organizationName:'Unsaved catalog fixture'}})
 expect(registered.ok()).toBe(true)
 const identity=(await (await page.request.get('/api/auth/me')).json()).data
 organizations.push(identity.organization.id);users.push(identity.user.id)
 const other=await db.organization.create({data:{name:'Other unsaved business',phone:randomUUID()}});organizations.push(other.id)
 await db.organizationUser.create({data:{organizationId:other.id,userId:identity.user.id,role:'owner'}})
 const otherStore=await db.store.create({data:{organizationId:other.id,name:'Other store'}})
 await db.register.create({data:{storeId:otherStore.id,name:'Other till',code:randomUUID()}})
 const a=await db.category.create({data:{organizationId:identity.organization.id,name:'Category original A'}}),b=await db.category.create({data:{organizationId:identity.organization.id,name:'Category original B'}})
 await page.goto('/products/categories')
 await page.getByRole('row').filter({hasText:a.name}).getByRole('button',{name:'Tahrirlash',exact:true}).click()
 await page.getByLabel('Kategoriya nomi').fill('Category unsaved A')
 await expect(page.getByRole('status').filter({hasText:'Saqlanmagan kategoriya'})).toBeVisible()
 page.once('dialog',dialog=>dialog.dismiss())
 await page.getByRole('row').filter({hasText:b.name}).getByRole('button',{name:'Tahrirlash',exact:true}).click()
 await expect(page.getByLabel('Kategoriya nomi')).toHaveValue('Category unsaved A')
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('row').filter({hasText:b.name}).getByRole('button',{name:'Tahrirlash',exact:true}).click()
 await expect(page.getByLabel('Kategoriya nomi')).toHaveValue(b.name)
 await expect(page.getByRole('status').filter({hasText:'Saqlanmagan kategoriya'})).toHaveCount(0)
 await page.getByLabel('Kategoriya nomi').fill('Category confirmed B')
 const endpoint='**/api/categories/'+b.id
 await page.route(endpoint,route=>route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({success:false,error:{code:'CONCURRENT_CONFLICT',message:'Fixture rejected save'}})}))
 await page.getByRole('button',{name:'Saqlash',exact:true}).click()
 await expect(page.getByRole('alert').filter({hasText:'Fixture rejected save'})).toBeVisible()
 await expect(page.getByLabel('Kategoriya nomi')).toHaveValue('Category confirmed B')
 await expect(page.getByRole('status').filter({hasText:'Saqlanmagan kategoriya'})).toBeVisible()
 await page.unroute(endpoint)
 await page.getByRole('button',{name:'Saqlash',exact:true}).click()
 await expect(page.getByRole('row').filter({hasText:'Category confirmed B'})).toBeVisible()
 await expect(page.getByRole('status').filter({hasText:'Saqlanmagan kategoriya'})).toHaveCount(0)
 await page.goto('/products/units')
 await page.getByLabel('Kod',{exact:true}).fill('unsaved_unit')
 await page.getByLabel('Nomi',{exact:true}).fill('Unsaved unit name')
 page.once('dialog',dialog=>dialog.dismiss())
 await page.getByRole('button',{name:'Bekor qilish',exact:true}).click()
 await expect(page.getByLabel('Nomi',{exact:true})).toHaveValue('Unsaved unit name')
 page.once('dialog',dialog=>dialog.dismiss())
 await page.getByRole('link',{name:'Mahsulotlarga qaytish',exact:true}).click()
 await expect(page).toHaveURL(/\/products\/units$/)
 await expect(page.getByLabel('Nomi',{exact:true})).toHaveValue('Unsaved unit name')
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'Bekor qilish',exact:true}).click()
 await expect(page.getByLabel('Kod',{exact:true})).toHaveValue('')
 await expect(page.getByRole('status').filter({hasText:'Saqlanmagan birlik'})).toHaveCount(0)
 const brandA=await db.brand.create({data:{organizationId:identity.organization.id,name:'Brand existing A'}}),brandB=await db.brand.create({data:{organizationId:identity.organization.id,name:'Brand existing B'}})
 await page.goto('/products/brands')
 await page.getByRole('button',{name:'Brendni tahrirlash: '+brandA.name,exact:true}).click()
 await page.getByLabel('Brend nomi').fill('Brand unsaved A')
 // Archiving another row must not clear the in-progress editor.
 await page.getByRole('button',{name:'Brend holati: '+brandB.name,exact:true}).click()
 await expect(page.getByLabel('Brend nomi')).toHaveValue('Brand unsaved A')
 await expect.poll(async()=>(await db.brand.findUniqueOrThrow({where:{id:brandB.id}})).isActive).toBe(false)
 page.once('dialog',dialog=>dialog.dismiss())
 await page.getByRole('link',{name:'Mahsulotlarga qaytish',exact:true}).click()
 await expect(page).toHaveURL(/\/products\/brands$/)
 await expect(page.getByLabel('Brend nomi')).toHaveValue('Brand unsaved A')
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('link',{name:'Mahsulotlarga qaytish',exact:true}).click()
 await expect(page).toHaveURL(/\/products$/)
 expect((await db.brand.findUniqueOrThrow({where:{id:brandA.id}})).name).toBe(brandA.name)
 await page.goto('/suppliers')
 await page.getByRole('button',{name:'Yangi yetkazib beruvchi',exact:true}).click()
 await page.getByRole('dialog').getByLabel('Nomi',{exact:true}).fill('Supplier unsaved contact')
 page.once('dialog',dialog=>dialog.dismiss())
 await page.keyboard.press('Escape')
 await expect(page.getByRole('dialog').getByLabel('Nomi',{exact:true})).toHaveValue('Supplier unsaved contact')
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('dialog').getByRole('button',{name:'Oynani yopish',exact:true}).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await page.goto('/customers')
 await page.getByRole('button',{name:"Yangi mijoz qo'shish",exact:true}).click()
 const customerDialog=page.getByRole('dialog')
 await customerDialog.getByLabel("Mijoz to'liq ismi *",{exact:true}).fill('Customer exact decimal')
 await customerDialog.getByLabel('Telefon raqami *',{exact:true}).fill('+998901234567')
 await customerDialog.getByLabel("Maksimal nasiya / kredit limiti (so'm)",{exact:true}).fill('999999999999.99')
 page.once('dialog',dialog=>dialog.dismiss())
 await customerDialog.getByRole('button',{name:'Bekor qilish',exact:true}).click()
 await expect(customerDialog.getByLabel("Maksimal nasiya / kredit limiti (so'm)",{exact:true})).toHaveValue('999999999999.99')
 const posted=page.waitForRequest(request=>request.url().endsWith('/api/customers')&&request.method()==='POST')
 await customerDialog.getByRole('button',{name:"Qo'shish",exact:true}).click()
 expect((await posted).postDataJSON().creditLimit).toBe('999999999999.99')
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await expect.poll(async()=>(await db.customer.findFirst({where:{organizationId:identity.organization.id,fullName:'Customer exact decimal'}}))?.creditLimit.toString()).toBe('999999999999.99')
 await page.goto('/products/units')
 await page.getByLabel('Nomi',{exact:true}).fill('Unsaved original business unit')
 page.once('dialog',dialog=>dialog.dismiss())
 await page.getByTitle('Tizimdan chiqish',{exact:true}).click()
 expect((await (await page.request.get('/api/auth/me')).json()).data.organization.id).toBe(identity.organization.id)
 await expect(page.getByLabel('Nomi',{exact:true})).toHaveValue('Unsaved original business unit')
 page.once('dialog',dialog=>dialog.dismiss())
 await page.getByLabel('Biznesni almashtirish').selectOption(other.id)
 expect((await (await page.request.get('/api/auth/me')).json()).data.organization.id).toBe(identity.organization.id)
 await expect(page.getByLabel('Nomi',{exact:true})).toHaveValue('Unsaved original business unit')
 let switchDialogs=0
 const acceptSwitch=async(dialog:import('@playwright/test').Dialog)=>{switchDialogs++;await dialog.accept()}
 page.on('dialog',acceptSwitch)
 await page.getByLabel('Biznesni almashtirish').selectOption(other.id)
 await expect(page).toHaveURL(/\/pos$/)
 await expect.poll(async()=>(await (await page.request.get('/api/auth/me')).json()).data.organization.id).toBe(other.id)
 page.off('dialog',acceptSwitch)
 expect(switchDialogs).toBe(1)


})
