test('Authenticator UI keeps secrets in memory, rotates backup codes and recovers with all-session logout',async({page})=>{
 const response=await page.request.post('/api/auth/register',{headers:{Origin:'https://localhost:3100'},data:{fullName:'TOTP browser owner',phone:'totp-browser-'+randomUUID(),password,organizationName:'TOTP browser business'}});expect(response.ok()).toBe(true)
 const me=(await(await page.request.get('/api/auth/me')).json()).data;orgs.push(me.organization.id);users.push(me.user.id)
 await page.goto('/security')
 const section=page.getByRole('region',{name:'Authenticator',exact:true})
 await expect(section.getByText('Authenticator ulanmagan',{exact:true})).toBeVisible()
 await section.getByLabel('Authenticator uchun joriy parol',{exact:true}).fill(password)
 await section.getByRole('button',{name:'Authenticator ulash',exact:true}).click()
 const key=section.getByLabel('Authenticator ulash kaliti',{exact:true});await expect(key).toBeVisible()
 const secret=(await key.textContent())!,totp=new TOTP({secret,digits:6,period:30})
 await expect(section.getByLabel('Authenticator uchun joriy parol',{exact:true})).toHaveValue('')
 await section.getByLabel('Authenticator tasdiqlash kodi',{exact:true}).fill(totp.generate({timestamp:Date.now()-30000}))
 await section.getByRole('button',{name:'Authenticatorni tasdiqlash',exact:true}).click()
 await expect(section.getByText('Authenticator ulangan',{exact:true})).toBeVisible()
 const backups=section.getByLabel('Zaxira kodlar',{exact:true})
 await expect(backups.locator('li code')).toHaveCount(10)
 const originalCodes=await backups.locator('li code').allTextContents()
 const stored=await page.evaluate(()=>JSON.stringify({local:{...localStorage},session:{...sessionStorage}}))
 expect(stored.includes(secret)).toBe(false);for(const code of originalCodes)expect(stored.includes(code)).toBe(false)
 await page.reload();await expect(section.getByText('Authenticator ulangan',{exact:true})).toBeVisible();await expect(backups).toHaveCount(0);await expect(key).toHaveCount(0)
 await section.getByLabel('Authenticator uchun joriy parol',{exact:true}).fill(password)
 await section.getByLabel('Zaxira kodlarni yangilash uchun Authenticator kodi',{exact:true}).fill(totp.generate())
 await section.getByRole('button',{name:'Zaxira kodlarni yangilash',exact:true}).click()
 await expect(backups.locator('li code')).toHaveCount(10)
 const replacement=(await backups.locator('li code').first().textContent())!
 expect(originalCodes.includes(replacement)).toBe(false)
 await section.getByRole('button',{name:'Kodlarni saqladim — oynadan tozalash',exact:true}).click();await expect(backups).toHaveCount(0)
 // Fault-inject availability only, retaining actual owned factor metadata.
 // The API integration test separately removes the real server key/flag.
 await page.route('**/api/auth/totp',async route=>{const actual=await route.fetch(),body=await actual.json();body.data.available=false;await route.fulfill({response:actual,json:body})})
 await section.getByRole('button',{name:'Authenticator holatini tekshirish',exact:true}).click()
 await expect(section.getByText('Authenticator hozir mavjud emas. Mavjud ulanishni zaxira kod bilan bekor qilish mumkin.',{exact:true})).toBeVisible()
 await expect(section.getByRole('button',{name:'Zaxira kodlarni yangilash',exact:true})).toBeDisabled()
 await section.getByLabel('Authenticator uchun joriy parol',{exact:true}).fill(password)
 await section.getByLabel('Authenticatorni tiklash uchun zaxira kod',{exact:true}).fill(replacement)
 await section.getByRole('button',{name:'Zaxira kod bilan ulanishni bekor qilish',exact:true}).click()
 await expect(page).toHaveURL(/\/login$/)
 expect(await db.session.count({where:{userId:me.user.id,revokedAt:null}})).toBe(0)
 expect(await db.totpFactor.count({where:{userId:me.user.id,revokedAt:null}})).toBe(0)
})
