import { test,expect } from '@playwright/test'
import { PrismaClient } from '@prisma/client'
import { randomUUID } from 'node:crypto'
const url=new URL(process.env.DATABASE_URL??'')
if(url.hostname!=='127.0.0.1'||url.port!=='55439'||url.pathname!=='/pos_test')throw new Error('Isolated test DB only')
const db=new PrismaClient(),orgs:string[]=[],users:string[]=[]
test.afterAll(async()=>{await db.organization.deleteMany({where:{id:{in:orgs}}});await db.user.deleteMany({where:{id:{in:users}}});await db.$disconnect()})
test('Ticket lost ACK recovers once, real internal reply tracks separately and unconfigured recovery never verifies',async({page})=>{
 const registration=await page.request.post('/api/auth/register',{headers:{Origin:'https://localhost:3100'},data:{fullName:'Ticket test owner',phone:'ticket-browser-'+randomUUID(),password:'test-only-password',organizationName:'Ticket browser business'}})
 expect(registration.ok()).toBe(true)
 const me=(await(await page.request.get('/api/auth/me')).json()).data;orgs.push(me.organization.id);users.push(me.user.id)
 await page.goto('/tickets')
 await expect(page.getByRole('heading',{name:'Yordam murojaatlari',exact:true})).toBeVisible()
 const form=page.getByRole('region',{name:'Yangi murojaat'})
 await form.getByLabel('Mavzu',{exact:true}).fill('Lost acknowledgment ticket')
 await form.getByLabel('Muammo tavsifi',{exact:true}).fill('Browser-only internal test; no external message or hardware integration')
 await form.getByLabel('Yangi murojaat darajasi',{exact:true}).selectOption('important')
 let lost=false
 await page.route('**/api/support/tickets',async route=>{if(route.request().method()==='POST'&&!lost){lost=true;const response=await route.fetch();expect(response.ok()).toBe(true);await route.abort('failed')}else await route.continue()})
 await form.getByRole('button',{name:'Murojaatni yuborish: oldindan ko‘rish'}).click()
 await form.getByRole('button',{name:'Amalni tasdiqlash',exact:true}).click()
 await expect.poll(()=>db.supportTicket.count({where:{organizationId:me.organization.id}})).toBe(1)
 await expect(form.getByRole('button',{name:'Original amalni qayta tekshirish'})).toBeEnabled()
 await page.reload()
 await form.getByRole('button',{name:'Original amalni qayta tekshirish'}).click()
 await expect(page.getByRole('heading',{name:'Lost acknowledgment ticket',exact:true})).toBeVisible()
 const ticket=await db.supportTicket.findFirstOrThrow({where:{organizationId:me.organization.id}})
 expect(await db.supportTicketEvent.count({where:{ticketId:ticket.id}})).toBe(1)
 expect(ticket.firstRespondedAt).toBeNull()
 await db.platformOperator.create({data:{userId:me.user.id,role:'support'}})
 await page.goto(`/tickets/${ticket.id}?scope=platform`)
 const command=page.getByRole('region',{name:'Murojaat amali'})
 await command.getByLabel('Javob yoki sabab',{exact:true}).fill('Test support operator replies inside the application')
 await command.getByRole('button',{name:'Murojaat amalini bajarish: oldindan ko‘rish'}).click()
 await command.getByRole('button',{name:'Amalni tasdiqlash',exact:true}).click()
 await expect.poll(async()=>!!(await db.supportTicket.findUniqueOrThrow({where:{id:ticket.id}})).firstRespondedAt).toBe(true)
 expect((await db.supportTicket.findUniqueOrThrow({where:{id:ticket.id}})).firstResolvedAt).toBeNull()
 await expect(command.getByRole('button',{name:'Murojaat amalini bajarish: oldindan ko‘rish'})).toBeVisible()
 await command.getByLabel('Murojaat amali',{exact:true}).selectOption('state')
 await command.getByLabel('Yangi holat',{exact:true}).selectOption('resolved')
 await command.getByLabel('Javob yoki sabab',{exact:true}).fill('Internal browser test resolution confirmed')
 await command.getByRole('button',{name:'Murojaat amalini bajarish: oldindan ko‘rish'}).click()
 await command.getByRole('button',{name:'Amalni tasdiqlash',exact:true}).click()
 await expect.poll(async()=>(await db.supportTicket.findUniqueOrThrow({where:{id:ticket.id}})).state).toBe('resolved')
 expect(await db.supportTicket.count({where:{organizationId:me.organization.id}})).toBe(1)
 expect(await db.supportTicketEvent.count({where:{ticketId:ticket.id}})).toBe(3)
 await page.goto('/forgot-password')
 await page.getByLabel('Telefon yoki e-mail',{exact:true}).fill(me.user.phone)
 const unavailable=page.waitForResponse(response=>response.url().includes('/api/auth/password-reset/request')&&response.request().method()==='POST')
 await page.getByRole('button',{name:'Tiklashni so‘rash',exact:true}).click()
 expect((await unavailable).status()).toBe(503)
 await expect(page.getByRole('alert').filter({hasText:'hali sozlanmagan'})).toBeVisible()
 expect(await db.verifiedContact.count({where:{userId:me.user.id}})).toBe(0)
 expect(await db.authChallenge.count({where:{userId:me.user.id}})).toBe(0)
})
