const dynamicRules = Object.entries(ROUTE_PERMISSIONS)
  .filter(([key]) => key.includes('['))
  .sort(([a], [b]) => (a.match(/\[/g)?.length ?? 0) - (b.match(/\[/g)?.length ?? 0))
  .map(([key, roles]) => {
    const [method, template] = key.split(' ')
    return { method, parts: template.split('/'), roles }
  })

export function routePermissionRoles(path: string, method: string): readonly BusinessRole[] | undefined {
  // Next.js implements HEAD through GET when no explicit HEAD handler exists.
  const verb = method
  const parts = path.split('/')
  const exact = ROUTE_PERMISSIONS[`${verb} ${path}`]
  if (exact) return exact
  const matched = dynamicRules.find(({ method: candidateMethod, parts: candidate }) => {
    if (candidateMethod !== verb) return false
    return candidate.length === parts.length && candidate.every((segment, index) =>
      /^\[[^\]]+\]$/.test(segment) ? parts[index].length > 0 : segment === parts[index])
  })?.roles
  return matched ?? (method === 'HEAD' ? routePermissionRoles(path, 'GET') : undefined)
}
